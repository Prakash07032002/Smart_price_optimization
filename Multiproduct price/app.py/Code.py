def forecast_future(model, last_window, scaler, months):

    preds = []
    current = last_window

    for i in range(months):

        pred = model.predict(current.reshape(1,6,1), verbose=0)
        preds.append(pred[0][0])

        current = np.append(current[1:], pred)

    preds = scaler.inverse_transform(np.array(preds).reshape(-1,1))

    return preds


